    events=[]
    for i in range(2):events.append({'schema_version':'openpine.market-event.1','sequence':i,'context_id':'primary','kind':'close','time':i*60000,'event_time':(i+1)*60000,'revision':0,'open':10.,'high':10.,'low':10.,'close':10.,'volume':1.})
