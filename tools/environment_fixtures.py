TIMES=[1709164740000,1709164800000,1709164920000,1709251200000]


def source(v,body,title='environment'):
    return f'//@version={v}\n'+('study' if v<5 else 'indicator')+f'("{title}")\n'+body+'\n'


def prepare():
    files={};cases=[]
    def put(name,value):files[name]=encode(value) if not isinstance(value,str) else value.encode('utf-8')
